"""Assemble the paper package: figures, tables, reports, docs, images.

Collects every artifact needed to write the paper into ``paper_package/``,
normalising names where useful, and writes a MANIFEST.md index.

    python tools/make_paper_package.py
"""

from __future__ import annotations

import io
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "paper_package"


def _copy(src: Path, dst_dir: Path, rename: str | None = None) -> str:
    dst_dir.mkdir(parents=True, exist_ok=True)
    target = dst_dir / (rename or src.name)
    shutil.copy2(src, target)
    return target.relative_to(PKG).as_posix()


def main() -> int:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    if PKG.exists():
        shutil.rmtree(PKG)
    PKG.mkdir()

    lines = [
        "# Paper package — smoke detection benchmark (FIRESENSE)",
        "",
        "Self-contained asset bundle for writing the paper. Everything was",
        "regenerated by the pipeline in this repository; the manifest below maps",
        "each asset to its source path and role.",
        "",
        "## 1. figures/ — final paper figures",
        "",
    ]

    # ---- figures -----------------------------------------------------------
    fig_descriptions = {
        "roc.png": "Frame-level ROC pooled over the 5 test splits, one curve per model (TCN AUC 0.674, GRU 0.595 on split01).",
        "roc_per_split.png": "ROC small multiples, one panel per test split, AUC annotated per model.",
        "pr.png": "Frame-level precision-recall pooled (TCN AP 0.693 vs GRU 0.634; 0.58 chance line).",
        "pr_per_split.png": "PR small multiples per split (AP annotated; split02 0.99 down to split04 0.56 — honest spread).",
        "reliability.png": "Reliability diagrams per (model, split), bars with per-bin counts, ECE/Brier in titles.",
        "delay.png": "Three-panel delay figure: (a) time-to-detection CDF per model (recall within t, log axis, endpoint markers), (b) per-video strips (box + split-coloured dots; misses as x censored at each video's duration), (c) false-alarms/hour with split-std error bars; rows sorted by median delay, TCN highlighted.",
        "dfire_transfer_roc.png": "Frame-level transfer probe of the spatial CNN to DFire still images (test-only): negative/odd transfer documented honestly — scores collapse to a 0.6–0.73 band on every class (smoke vs none AUROC 0.42 max / 0.46 mean; vs fire distractors 0.69 / 0.58).",
        "qualitative.png": "Qualitative grid: positive video (testpos10, onset frame 0) + negative video (testneg02 with its documented 12 s false alarm); decision log replaces the obsolete 'temporal evidence' panel.",
    }
    for fig in sorted((ROOT / "results" / "figures").glob("*.png")):
        _copy(fig, PKG / "figures")
        lines.append(f"- `{fig.name}` — {fig_descriptions.get(fig.name, '')}")
    lines += [
        "",
        "Commands: `python -m src.visualization.plot_roc` / `plot_pr` / `plot_reliability` / `plot_delay`,",
        "and `python -m src.visualization.make_qualitative_grid --model results/raw/tcn_split01_seed42/model.pt --spatial-checkpoint results/raw/spatial_split01_seed42/model.pt --video data/raw/firesense_smoke/pos/testpos10.826.avi --video data/raw/firesense_smoke/neg/testneg02.808.avi`.",
        "",
        "## 2. architecture/ — diagrams",
        "",
    ]

    # ---- architecture diagrams --------------------------------------------
    import subprocess

    subprocess.run(
        [sys.executable, str(ROOT / "tools" / "make_architecture.py")], check=True
    )
    for arch in sorted((PKG / "architecture").glob("*.png")):
        lines.append(f"- `{arch.name}`")
    lines += [
        "",
        "## 3. tables/ — quantitative tables",
        "",
    ]

    # ---- tables ------------------------------------------------------------
    table_descriptions = {
        "table1_main_accuracy.csv": "Table 1 — video-level accuracy/false alarms/delay per model (TCN vs baselines).",
        "table2_edge_deployment.csv": "Table 2 — end-to-end edge results: latency percentiles, system FPS, energy (RTX 5070 laptop CPU-thread-time).",
        "table3_quantization.csv": "Table 3 — FP16 vs INT8 quantisation vs FP32 (accuracy drift + size).",
        "table4_generalization.csv": "Table 4 — cross-dataset generalisation (empty — documented §8b limitation: no external dataset downloaded).",
        "table5_ablations.csv": "Table 5 — ablations over decisions (score source, calibration, policy rules).",
        "summary_over_splits.csv": "Per-model mean±std of every metric over the 5 splits (recall 0.60, FA/h 85.3, delay 2.47 s for the TCN).",
        "summary_over_splits.json": "Same as the CSV in structured form.",
        "statistics_video_recall_split0X.json": "Wilcoxon + bootstrap CIs (unit: video) for video recall, one per split.",
        "statistics_false_alarms_per_hour_split0X.json": "Statistics for FA/h, one per split.",
        "statistics_detection_delay_split0X.json": "Statistics for detection delay, one per split.",
    }
    for table in sorted((ROOT / "results" / "tables").iterdir()):
        _copy(table, PKG / "tables")
        lines.append(f"- `{table.name}`")
    lines += [
        "",
        "## 4. data_reports/ — raw evaluation reports (JSON/CSV/NPZ)",
        "",
        "Per-split machine-readable reports; `*_frames.npz` hold the frame scores/labels used by ROC/PR regeneration.",
        "",
    ]
    raw = ROOT / "results" / "raw"
    n = 0
    for f in sorted(raw.glob("*")):
        if f.is_file() and f.suffix in {".json", ".csv", ".npz"}:
            _copy(f, PKG / "data_reports")
            n += 1
    # DFire transfer probe (frame-level, negative-transfer documentation).
    for f in sorted((raw / "dfire_frame_transfer_seed42").glob("*")):
        _copy(f, PKG / "data_reports", rename=f"dfire_frame_transfer_seed42__{f.name}")
        n += 1
    lines.append(f"- {n} files (sweeps per split + seed, frame/video/calibration evals, streaming equivalence checks, latency & energy benchmarks, per-campaign summary CSVs, DFire frame-transfer probe)")
    lines += [
        "",
        "## 5. training_reports/ — per run directory (reports)",
        "",
    ]
    lines_desc = []
    for d in sorted(raw.iterdir()):
        if not d.is_dir():
            continue
        files = sorted(d.glob("*.json"))
        if not files:
            continue
        for f in files:
            _copy(f, PKG / "training_reports" / d.name)
        lines_desc.append(
            f"- `{d.name}/` — {', '.join(f.name for f in files)}"
        )
    lines += lines_desc
    lines += [
        "",
        "Note: duplicated run folders with `__hash` suffixes are distinct re-trainings recorded by the experiment registry; they are kept for provenance.",
        "",
        "## 6. quantization/ — model compression reports",
        "",
    ]
    for q in sorted(raw.glob("quantized_*")):
        for f in q.glob("*.json"):
            lines.append(f"- `{_copy(f, PKG / 'quantization', rename=f'{q.name}__{f.name}')}`")

    # ---- edge benchmarks (files already land in data_reports) ---------------
    lines += [
        "",
        "## 7. docs/ — protocol & summary documents",
        "",
    ]
    doc_map = {
        "paper/results_summary.md": "Filled results document (headline numbers, all tables' fill blocks, §8b limitation, conclusion).",
        "paper/benchmark_protocol.md": "Pre-registered protocol: splits, metrics, delay definition, edge measurement rules.",
        "paper/dataset_card.md": "Dataset properties, onset-annotation protocol, preprocessing table.",
        "paper/methods_notes.md": "Mathematical description of every component (Kalman, HSV, CNN, TCN, policy).",
        "paper/model_card.md": "Model card — intended use, metrics, limitations.",
        "README.md": "Repository overview and how to reproduce.",
        "configs/benchmark_edge.yaml": "Single source of truth for evaluation settings (front end, policy, edge).",
        "data/annotations/onsets.csv": "Manual smoke-onset annotations (CSV with provenance comments).",
        "data/manifests/firesense_videos.csv": "Locked video manifest (22 videos).",
        "data/manifests/splits.csv": "Locked split assignment per video.",
    }
    for src, desc in doc_map.items():
        target_rel = _copy(ROOT / src, PKG / "docs", rename=Path(src).name)
        lines.append(f"- `{target_rel}` — {desc}")

    # Root README: self-contained project description with values & comparisons.
    readme_src = ROOT / "paper" / "paper_package_README.md"
    if readme_src.exists():
        _copy(readme_src, PKG, rename="README.md")
        lines.append(
            "- `../README.md` — package root README: research question, system, dataset/protocol, "
            "all headline values and model comparisons (operating point, matched recall, calibration, "
            "edge/energy, quantisation, DFire transfer), limitations, folder map, reproduction commands."
        )

    lines += [
        "",
        "## 8. annotation_sheets/ — manual-onset contact sheets",
        "",
        "The 4×4 contact sheets used to annotate the smoke onsets (one PNG per positive video), enabling an auditor to re-check every onset value. Image sizes are large (~1.8 MB each); fine sheets were omitted for space and stay in `data/annotations/sheets_fine/`.",
        "",
    ]
    for sheet in sorted((ROOT / "data" / "annotations" / "sheets").glob("*.png")):
        _copy(sheet, PKG / "annotation_sheets")
        lines.append(f"- `{sheet.name}`")

    lines += [
        "",
        "## 9. Reproducing everything",
        "",
        "- Test suite: `python -m pytest tests` (77/77 pass).",
        "- Full evaluation chain used throughout: `experiments/run_pipeline.py` (five split runs), `experiments/run_reporting.py`, `experiments/run_edge_benchmark.py`.",
        "- Seed locked at 42; thresholds and calibration fitted on validation only; the test manifest is read-only by design.",
        "",
        "## 10. Headline numbers (for quick reference)",
        "",
        "- False alarms/h: **235.8 → 85.3 (−63.8 %)** vs frame-only CNN fixed-threshold baseline.",
        "- Video recall: **0.500 → 0.600**; mean delay: **5.85 s → 2.47 s (−57.7 %)**.",
        "- Edge: **165 FPS** end-to-end, p50 latency **6.06 ms**, p99 **7.43 ms**, 0 dropped frames; energy ≈ 1.15 J/frame (CPU-thread-time estimate).",
        "- Quantisation: FP16 safe (logit Δ 9e-4, 23 % smaller), INT8 degrades (Δ 0.022).",
        "- Streaming == offline on every checked video (7/7 on splits 01–02).",
        "- DFire frame-level transfer (test-only probe): **negative transfer** — spatial CNN probabilities collapse across all image classes (see §8b of results_summary.md); mixed-domain candidate training is future work.",
        "- Known limitations: frame AUROC swings 0.56–0.99 across splits; GRU underperforms; cross-dataset video-level evaluation not yet available.",
    ]

    manifest = PKG / "MANIFEST.md"
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {manifest}")
    total = sum(f.stat().st_size for f in PKG.rglob("*") if f.is_file())
    print(f"package: {PKG} — {total / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
